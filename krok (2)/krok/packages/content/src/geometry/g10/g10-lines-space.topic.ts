// ───────────── куб: координати та взаємне розміщення прямих ─────────────

type V3 = [number, number, number]
const P3: Record<string, V3> = {
  A: [0, 0, 0],
  B: [1, 0, 0],
  C: [1, 1, 0],
  D: [0, 1, 0],
  'A₁': [0, 0, 1],
  'B₁': [1, 0, 1],
  'C₁': [1, 1, 1],
  'D₁': [0, 1, 1],
}
const sub = (a: V3, b: V3): V3 => [a[0] - b[0], a[1] - b[1], a[2] - b[2]]
const cross = (a: V3, b: V3): V3 => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]
const dot = (a: V3, b: V3): number => a[0] * b[0] + a[1] * b[1] + a[2] * b[2]
const isZero = (v: V3) => v[0] === 0 && v[1] === 0 && v[2] === 0

type Rel = 'intersect' | 'parallel' | 'skew' | 'same'
type Line = [string, string]

function relation(l1: Line, l2: Line): Rel {
  const p1 = P3[l1[0]]
  const p2 = P3[l2[0]]
  const d1 = sub(P3[l1[1]], p1)
  const d2 = sub(P3[l2[1]], p2)
  const c = cross(d1, d2)
  if (isZero(c)) return isZero(cross(sub(p2, p1), d1)) ? 'same' : 'parallel'
  return dot(sub(p2, p1), c) === 0 ? 'intersect' : 'skew'
}

const EDGES: Line[] = [
  ['A', 'B'], ['B', 'C'], ['C', 'D'], ['D', 'A'],
  ['A₁', 'B₁'], ['B₁', 'C₁'], ['C₁', 'D₁'], ['D₁', 'A₁'],
  ['A', 'A₁'], ['B', 'B₁'], ['C', 'C₁'], ['D', 'D₁'],
]
const DIAGS: Line[] = [
  ['A', 'C'], ['B', 'D'], ['A₁', 'C₁'], ['B₁', 'D₁'],
  ['A', 'B₁'], ['A₁', 'B'], ['D', 'C₁'], ['D₁', 'C'],
  ['A', 'D₁'], ['A₁', 'D'], ['B', 'C₁'], ['B₁', 'C'],
]
const ALL_LINES: Line[] = [...EDGES, ...DIAGS]
const nm = (l: Line) => `${l[0]}${l[1]}`

const pairsByRel: Record<'intersect' | 'parallel' | 'skew', [Line, Line][]> = { intersect: [], parallel: [], skew: [] }
for (let i = 0; i < ALL_LINES.length; i++) {
  for (let j = i + 1; j < ALL_LINES.length; j++) {
    const r = relation(ALL_LINES[i], ALL_LINES[j])
    if (r !== 'same') pairsByRel[r].push([ALL_LINES[i], ALL_LINES[j]])
  }
}

