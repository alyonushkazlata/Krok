const LETTERS = ['A', 'B', 'C', 'D', 'E', 'F', 'K', 'L', 'M', 'N', 'P', 'Q', 'R', 'S', 'T']
const pickNames = (rng: Rng, n: number): string[] => rng.shuffle(LETTERS).slice(0, n)

/** Усі прийнятні способи написати назву вершини на кшталт C₁: C₁, C1, c1, кирилична С1… */
function nameVariants(v: string): string[] {
  const base = v[0]
  const hasSub = v.length > 1
  const cyr: Record<string, string> = { A: 'А', B: 'В', C: 'С' }
  const letters = [base, base.toLowerCase(), ...(cyr[base] ? [cyr[base], cyr[base].toLowerCase()] : [])]
  const out: string[] = []
  for (const l of letters) {
    if (hasSub) out.push(`${l}₁`, `${l}1`)
    else out.push(l)
  }
  return out
}

const C = (n: number, k: number): number => {
  let r = 1
  for (let i = 1; i <= k; i++) r = (r * (n - k + i)) / i
  return Math.round(r)
}

