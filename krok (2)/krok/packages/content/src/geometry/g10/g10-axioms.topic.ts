const CUBE: Record<string, [number, number]> = {
  A: [0, 0],
  B: [3, 0],
  C: [4.2, 1],
  D: [1.2, 1],
  'A₁': [0, 3],
  'B₁': [3, 3],
  'C₁': [4.2, 4],
  'D₁': [1.2, 4],
}

function cubeFigure(highlight?: { pts: string[]; fill: Color }, extra: FigureItem[] = [], caption?: string): Figure {
  const solid: [string, string][] = [
    ['A', 'B'], ['B', 'C'], ['A', 'A₁'], ['B', 'B₁'], ['C', 'C₁'], ['A₁', 'B₁'], ['B₁', 'C₁'], ['C₁', 'D₁'], ['A₁', 'D₁'],
  ]
  const hidden: [string, string][] = [['A', 'D'], ['D', 'C'], ['D', 'D₁']]
  const items: FigureItem[] = []
  if (highlight) items.push({ t: 'poly', pts: highlight.pts, fill: highlight.fill, stroke: false })
  for (const [a, b] of solid) items.push({ t: 'seg', a, b })
  for (const [a, b] of hidden) items.push({ t: 'seg', a, b, style: 'dashed' })
  items.push(...extra)
  return figure(CUBE, items, { width: 300, caption, labelOffsets: { 'B₁': [-14, 14], D: [-2, 14], 'D₁': [-10, -12], 'C': [4, 4] } })
}

