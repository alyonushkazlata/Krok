/** Числова пряма з виділеною множиною (для малюнків у теорії). */
function numberLine(ticks: number[], ivs: Iv[], lo: number, hi: number): Figure {
  const items: FigureItem[] = [{ t: 'arrow', a: [lo, 0], b: [hi, 0] }]
  for (const i of ivs) {
    const a = i.lo === -Infinity ? lo + 0.2 : i.lo
    const b = i.hi === Infinity ? hi - 0.2 : i.hi
    if (a < b) items.push({ t: 'seg', a: [a, 0], b: [b, 0], style: 'bold', color: 'green' })
    if (i.lo !== -Infinity) items.push({ t: 'dot', at: [i.lo, 0], hollow: !i.lc, color: 'green' })
    if (i.hi !== Infinity) items.push({ t: 'dot', at: [i.hi, 0], hollow: !i.hc, color: 'green' })
  }
  for (const t of ticks) items.push({ t: 'text', at: [t - 0.12, -0.6], text: String(t) })
  return { view: [lo - 0.3, -1, hi + 0.3, 1], width: 460, items }
}

