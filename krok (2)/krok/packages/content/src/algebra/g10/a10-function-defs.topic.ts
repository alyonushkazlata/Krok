interface Iv {
  lo: number
  hi: number
  lc: boolean
  hc: boolean
}
const S = (x: number) => (x === -Infinity ? '-inf' : x === Infinity ? '+inf' : String(x))
const T = (x: number) => (x === -Infinity ? '-\\infty' : x === Infinity ? '+\\infty' : num(x))
const ivSpec = (ivs: Iv[]) => ivs.map((i) => `${i.lc ? '[' : '('}${S(i.lo)}; ${S(i.hi)}${i.hc ? ']' : ')'}`).join(' U ')
const ivTex = (ivs: Iv[]) => ivs.map((i) => `${i.lc ? '[' : '('}${T(i.lo)};\\, ${T(i.hi)}${i.hc ? ']' : ')'}`).join(' \\cup ')
const iv = (lo: number, hi: number, lc: boolean, hc: boolean): Iv => ({ lo, hi, lc: lo === -Infinity ? false : lc, hc: hi === Infinity ? false : hc })

